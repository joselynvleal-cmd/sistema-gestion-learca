<!-- Script JavaScript para el carrusel con control automático y manual -->
<script>
let currentSlide = 0;
const slides = document.querySelectorAll('.slide-trabajo');
const indicadores = document.querySelectorAll('.indicador-slide');
let autoSlideInterval;

function mostrarSlideCard(index) {
    if (slides.length === 0) return;
    
    slides.forEach(s => {
        s.classList.remove('active');
        s.style.opacity = '0';
    });
    
    indicadores.forEach(ind => {
        ind.style.width = '6px';
        ind.style.background = 'rgba(255, 253, 253, 0.5)';
    });

    currentSlide = (index + slides.length) % slides.length;
    
    slides[currentSlide].classList.add('active');
    slides[currentSlide].style.opacity = '1';
    
    if(indicadores[currentSlide]) {
        indicadores[currentSlide].style.width = '14px';
        indicadores[currentSlide].style.background = '#00FF87';
    }
}

function cambiarSlideCard(index) {
    mostrarSlideCard(index);
    reiniciarTemporizador(); // Reinicia el tiempo al hacer clic manual
}

function moverSlide(direccion) {
    mostrarSlideCard(currentSlide + direccion);
    reiniciarTemporizador(); // Reinicia el tiempo al usar las flechas
}

// Función para el cambio automático cada 4 segundos
function iniciarTemporizador() {
    if (slides.length > 0) {
        autoSlideInterval = setInterval(() => {
            mostrarSlideCard(currentSlide + 1);
        }, 4000);
    }
}

function reiniciarTemporizador() {
    clearInterval(autoSlideInterval);
    iniciarTemporizador();
}

// Iniciar carrusel al cargar
iniciarTemporizador();
</script>